"""Builds src/data.js and src/daily.json from the course content in this folder.
Run: python3 content/build_data.py (from desktop/)."""
import json, os, runpy, datetime

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "src")
weeks = json.load(open(os.path.join(HERE, "weeks.json"), encoding="utf8"))
L = runpy.run_path(os.path.join(HERE, "lessons.py"))
X = runpy.run_path(os.path.join(HERE, "extra_content.py")) if os.path.exists(os.path.join(HERE, "extra_content.py")) else {"STORY": [], "INTERVIEW": [], "SPELL": []}

for w in weeks:
    w["ej"] = [e.replace("I'm Natalia and I'm from", "My name is ___ and I'm from") for e in w["ej"]]
    missing = [v for v in w["vocab"] if v not in L["MEANINGS"]]
    assert not missing, (w["n"], missing)
    assert len(L["GRAMMAR"][w["n"]]) >= 6 and len(L["BUILD"][w["n"]]) >= 6, w["n"]

seed = [
    {"mal": "I have 20 years", "bien": "I'm 20 years old", "porque": "La edad va con to be"},
    {"mal": "the last weekend i travel", "bien": "Last weekend I traveled", "porque": "Pasado con -ed, sin 'the'"},
    {"mal": "in December i travel", "bien": "In December I'm going to travel", "porque": "Futuro con going to"},
    {"mal": "my mother and your family", "bien": "my mother and her family", "porque": "his (de él), her (de ella)"},
    {"mal": "I like play tennis", "bien": "I like playing tennis", "porque": "Después de like va -ing"},
    {"mal": "my meta is", "bien": "my goal is", "porque": "Falso amigo"},
    {"mal": "take a breakfast", "bien": "have breakfast", "porque": "Las comidas van con have"},
    {"mal": "for sleep", "bien": "to sleep", "porque": "Para + verbo = to + verbo"},
]
extra = {
    "meanings": L["MEANINGS"],
    "grammar": {str(k): v for k, v in L["GRAMMAR"].items()},
    "build": {str(k): [{"es": es, "en": en} for es, en in v] for k, v in L["BUILD"].items()},
    "seedErrors": seed,
}
js = "// Generated by content/build_data.py. Edit the files in content/ instead.\n"
js += "const WEEKS=" + json.dumps(weeks, ensure_ascii=False) + ";\n"
js += "const EXTRA=" + json.dumps(extra, ensure_ascii=False) + ";\n"
for name in ("STORY", "INTERVIEW", "SPELL"):
    js += "const " + name + "=" + json.dumps(X[name], ensure_ascii=False) + ";\n"
open(os.path.join(SRC, "data.js"), "w", encoding="utf8").write(js)

# Daily reminder text: today's topic and a phrase of the day, from 17 Oct 2026 to 3 Jan 2027.
W1 = datetime.date(2026, 10, 19)
daily = {}
d = datetime.date(2026, 10, 17)
while d <= datetime.date(2027, 1, 3):
    n = max(1, min(11, (d - W1).days // 7 + 1)) if d >= W1 else 1
    w = weeks[n - 1]
    i = d.weekday()
    v = w["vocab"][(i * 2 + (d - W1).days // 7) % len(w["vocab"])]
    tema = w["dias"][i] if d >= W1 else "Test de nivel y primera conversación"
    daily[d.isoformat()] = {"tema": tema.split(":")[0], "en": v, "es": L["MEANINGS"][v]}
    d += datetime.timedelta(days=1)
json.dump(daily, open(os.path.join(SRC, "daily.json"), "w", encoding="utf8"), ensure_ascii=False)
print("data.js", os.path.getsize(os.path.join(SRC, "data.js")), "bytes;", len(daily), "days")
